"""Build request_map.tex for the exhibit book from the three blocks' TRACKER.md files.

Book tooling only (the exhibits themselves are Stata). Run from this folder:  python3 make_request_map.py
For each of Deasy's rows: the row verbatim, then every sub-request (tracker item) with the exhibits that answer it,
the book pages of those exhibits (LaTeX \\pageref to the labels set by \\expage) and the status.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
BLOCKS = [
    ("R1", "block-r1-paris-internationalisation", 10),
    ("R2", "block-r2-internationalisation-energy-efficiency", 10),
    ("R3", "block-r3-energy-emissions-correlates", 9),
]
# Deasy's rows, verbatim (source Word row; also in the blocks' TRACKER.md headers)
ROWS = {
    "R1": ("How internationalized firms respond to climate commitment?? Do they adjust their energi use, emisi, dan juga "
           "internationalization strategy-nya? Do global climate commitments reach the factory floor? Did internationally "
           "engaged firms change their environmental behaviour more strongly after the Paris Agreement? Outcome variables: "
           "VA/energy use, scope 1, scope 2, total; VA/emisi, scope 1, scope 2, total; Energi use, scope 1, 2, total; Emisi, "
           "scope 1, 2, total; GJ/emisi, scope 1, 2, total; Co2/va; Gj/va; Electricity; Self generation.",
           "Matching per year: export vs non export, import vs non import, fdi vs non fdi. DID. Apakah mungkin dengan "
           "staggered did?? Alternative: Freeze internationalisation status sebelum Paris, misalnya average 2013–14: pre "
           "exporters x year; 2015 transition year; 2016+ post; Firm FE + industry×year FE + province×year FE. "
           "Matching/entropy balancing dapat digunakan sebagai robustness untuk membuat pre-Paris groups comparable.",
           "Sesuai diskusi jumat (28 august), karena kita gak bs tau first time exporting/importing/fdi nya, kita bs coba "
           "dengan method matching yearly.. dan dicompare bagaimana behaviour mereka toward energy use, emisi, ataupun "
           "ekspor, impor, fdi…"),
    "R2": ("Intertionalized and energy efficiency", "Stagged did",
           "Mirip dengan paper kita sebelumnya hanya Ganti tahun…"),
    "R3": ("Siapa yang reduce energy use and emisi? Lebih ke determinan motivasi apa yg membuat firms respond to climate "
           "commitment.. Tambahan: Siapa yang impor lebih banyak (EGs) environment goods list (termasuk solar panel, dll)",
           "FE", "Bukan kausal, tp mengetahui firms mana yg respond thd climate and motivasinya apa"),
}
STATUS_RE = re.compile(r"^(done on this dataset|done in the R2 block|done, descriptive|done, with caveat|done: checks run for every exhibit, mixed results|done|partial|unavailable)")


def tex(s):
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in [("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("$", "\\$"),
                 ("−", "$-$"), ("≥", "$\\ge$"), ("≤", "$\\le$"), ("→", "$\\to$"),
                 ("…", "\\ldots{}"), ("×", "$\\times$"), ("–", "--"), ("—", "---")]:
        s = s.replace(a, b)
    return s


def exhibits(cell, row, n_in_row):
    """Exhibit IDs named in a tracker cell, ranges 'R1-02 to R1-06' expanded; 'All R3 files' = every exhibit."""
    if re.search(r"\bAll R\d files\b", cell):
        return [f"{row}-{i:02d}" for i in range(1, n_in_row + 1)]
    out = []
    for a, b in re.findall(r"(R\d-\d\d)\s+to\s+(R\d-\d\d)", cell):
        p, i, j = a[:2], int(a[3:]), int(b[3:])
        out += [f"{p}-{k:02d}" for k in range(i, j + 1)]
    out += re.findall(r"R\d-\d\d", re.sub(r"R\d-\d\d\s+to\s+R\d-\d\d", "", cell))
    seen, res = set(), []
    for e in sorted(out, key=lambda x: (x[:2], int(x[3:]))):
        if e not in seen:
            seen.add(e)
            res.append(e)
    return res


def runs(ids):
    """Group consecutive exhibits of the same row: [['R1-02','R1-03','R1-04'], ['R1-08']]."""
    groups = []
    for e in ids:
        if groups and groups[-1][-1][:2] == e[:2] and int(groups[-1][-1][3:]) + 1 == int(e[3:]):
            groups[-1].append(e)
        else:
            groups.append([e])
    return groups


def fmt_ids(ids):
    return ", ".join(g[0] if len(g) == 1 else (f"{g[0]}, {g[1]}" if len(g) == 2 else f"{g[0]}--{g[-1][3:]}")
                     for g in runs(ids)) or "---"


def fmt_pages(ids):
    parts = []
    for g in runs(ids):
        if len(g) <= 2:
            parts += [f"\\pageref{{ex:{e}}}" for e in g]
        else:
            parts.append(f"\\pageref{{ex:{g[0]}}}--\\pageref{{ex:{g[-1]}}}")
    return ", ".join(parts) or "---"


lines = [
    "% Generated by make_request_map.py from the blocks' TRACKER.md files -- edit those, then re-run the script.",
    "\\section*{Deasy's requests and where each is answered}",
    "\\addcontentsline{toc}{section}{Deasy's requests and where each is answered}",
    "{\\small Every row of Deasy's request list (R1--R3), verbatim, then every sub-request inside it (the items of the "
    "block's \\texttt{TRACKER.md}), the exhibits that answer it, the pages in this book, and the status: "
    "\\textbf{done} = answered on this dataset; \\textbf{partial} = answered in part (the page says what is missing); "
    "\\textbf{unavailable} = this dataset cannot answer it (the page says why). Items in brackets are ours: what the method "
    "Deasy names needs (R1, R2) or the possible motives we tested (R3). ID letters: Q = question, O = outcome, "
    "G = group compared, T = start event, S = strategy, N = notes. Page numbers are links.}\\par\\medskip",
    "\\footnotesize",
    "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{1.2cm}>{\\raggedright\\arraybackslash}p{7.0cm}>{\\raggedright\\arraybackslash}p{3.4cm}>{\\raggedright\\arraybackslash}p{1.9cm}>{\\raggedright\\arraybackslash}p{2.1cm}@{}}",
    "\\toprule ID & Deasy's sub-request (verbatim; brackets = ours) & Answered by & Pages & Status\\\\ \\midrule \\endhead",
    "\\bottomrule \\endfoot",
]
counts = {}
for row, folder, n in BLOCKS:
    req, strat, notes = ROWS[row]
    lines.append(f"\\multicolumn{{5}}{{@{{}}p{{\\linewidth}}@{{}}}}{{\\rule{{0pt}}{{3ex}}\\textbf{{{row}}}\\quad "
                 f"\\textit{{Request:}} ``{tex(req)}'' \\textit{{Strategy:}} ``{tex(strat)}'' \\textit{{Notes:}} ``{tex(notes)}''}}\\\\[2pt] \\midrule")
    for line in (HERE.parent / folder / "TRACKER.md").read_text().splitlines():
        if not re.match(rf"^\| {row}\.\w+ \|", line):
            continue
        c = [x.strip() for x in line.strip().strip("|").split(" | ")]
        iid, item, exh_cell, status = c[0], c[1], c[2], c[3]
        m = STATUS_RE.match(status)
        st = m.group(1) if m else status.split("(")[0].strip()
        key = re.match(r"[a-z]+", st).group(0)
        counts.setdefault(row, {}).setdefault(key, 0)
        counts[row][key] += 1
        ids = exhibits(exh_cell, row, n) if exh_cell not in ("—", "-", "") else []
        item_tex = tex(item)
        if re.match(r"R3\.Q3[a-o]$", iid):
            item_tex = item_tex.replace("\\ldots{} ", "(possible motive:) ", 1)
        lines.append(f"{tex(iid)} & {item_tex} & {fmt_ids(ids)} & {fmt_pages(ids)} & {tex(st)}\\\\")
    lines.append("\\midrule")
lines[-1] = ""
lines.append("\\end{longtable}")
summary = "; ".join(f"{r}: " + ", ".join(f"{v} {k}" for k, v in sorted(d.items())) for r, d in counts.items())
lines.append(f"\\normalsize\\par\\smallskip{{\\small Item counts --- {summary}.}}")
(HERE / "request_map.tex").write_text("\n".join(lines) + "\n")
print("request_map.tex written:", summary)
