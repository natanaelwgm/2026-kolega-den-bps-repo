#!/usr/bin/env python3
"""E064: compile explicit definitions into native Stata labels and notes."""
import csv
import hashlib
import json
from pathlib import Path
import pandas as pd
from definitions import ROOT, VERSION, describe, contract, COUNTS, PERCENTAGES, IDENTITY

def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def write_json(p,x): Path(p).write_text(json.dumps(x,indent=2)+'\n')
def stata_literal(text):
    # All definitions are our reviewed plain text, not executable Stata syntax.
    if any(c in text for c in ['"','`','$','\n','\r']): raise ValueError(text)
    return '"'+text+'"'

def formula(spec):
    args=spec['inputs']; op=spec['op']
    if op=='alias': return args[0]+' on the inherited nonmissing sample'
    if op=='constant': return args[0]+' * '+str(spec['constants'][0])
    if op=='product': return ' * '.join(args)
    if op=='difference': return ' - '.join(args)
    if op=='sum_strict': return ' + '.join(args)+' (all inputs required)'
    if op=='sum_nonnegative': return 'sum of observed nonnegative components: '+', '.join(args)+'; all missing stays missing'
    if op=='sum_source_valid': return 'sum of nonnegative components with source state 0/1: '+', '.join(args)+'; all missing stays missing'
    if op=='fallback': return args[0]+' if observed nonnegative; otherwise '+args[1]
    if op=='ratio': return args[0]+' / '+args[1]+' on inherited admissible domain'
    if op=='log': return 'ln('+args[0]+') for positive finite input'
    raise ValueError(op)

def compile_metadata(input_file, out):
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    with pd.io.stata.StataReader(input_file) as reader:
        names=list(reader.variable_labels())
    if len(names)!=516: raise ValueError('Expected reviewed 516-variable schema; update contract explicitly')
    base, derived = contract(names)
    evidence={}
    with (ROOT/'downstream/contracts/variable_year_evidence.csv').open() as f:
        for r in csv.DictReader(f): evidence.setdefault(r['variable'],[]).append(r)
    rows=[]
    for n in names:
        d=describe(n)
        assert 0<len(d['label'])<=80
        d['formula']=formula(derived[n]) if n in derived else ''
        if n.startswith('dev_nominal_'):
            mode='Computed by G1 from masked inputs and fictional panel; no post-estimation perturbation.'
        elif n in IDENTITY or n in ['year','source_year']:
            mode='Release identity/calendar metadata; no actual-company linkage claim.'
        elif n in derived:
            mode='Recomputed from masked inputs; original nonmissing domain retained. Derived changes need not stay within the primary 20-30% band.'
        elif n in base or n in COUNTS or n in PERCENTAGES:
            mode='Seeded numeric masking before G1; primary target +/-20-30%, with documented integer/boundary exceptions. Not the actual reported value.'
        else:
            mode='Source category, status, availability count, or fixed assumption retained. Threshold/status flags describe the pre-mask source and are not automatically recomputed from changed numeric values.'
        d['release_treatment']=mode
        d['annual_evidence']=''
        ev=evidence.get(n,[])
        if ev:
            units=sorted({r['candidate_unit'] for r in ev if r['candidate_unit']})
            statuses=sorted({r['release_status'] for r in ev})
            d['annual_evidence']='Candidate units: '+', '.join(units)+'. Release states: '+', '.join(statuses)+'. Full annual rows: downstream/contracts/variable_year_evidence.csv.'
        d['note']='G1META: '+d['definition']+' Unit: '+d['unit']+'. '+mode
        if d['formula']: d['note']+=' Stored-value formula after masking: '+d['formula']+'.'
        if d['annual_evidence']: d['note']+=' '+d['annual_evidence']
        d['note']+=' Source: '+d['source']+'.'
        stata_literal(d['note']);stata_literal(d['label'])
        rows.append(d)
    cols=list(rows[0])
    with (out/'variable_dictionary.csv').open('w',newline='') as f:
        writer=csv.DictWriter(f,cols);writer.writeheader();writer.writerows(rows)
    do=['version 17','set varabbrev off','* Generated by E064; apply metadata only. Never change values/order/types.',
        'unab g1meta_vars : _all', 'local g1meta_count : word count `g1meta_vars\'',
        'assert `g1meta_count\'==516']
    verify=['version 17','* E066 native serialized-metadata assertions; read only.']
    for d in rows:
        n=d['name'];label=stata_literal(d['label']);note=stata_literal(d['note'])
        do += [f'confirm variable {n}',f'label variable {n} {label}',
               f'char {n}[g1_definition] {stata_literal(d["definition"])}',
               f'char {n}[g1_units] {stata_literal(d["unit"])}',
               f'local g1meta_note : char {n}[g1_metadata_note]',
               'if "`g1meta_note\'"=="" {',
               f'    notes {n}: {d["note"]}',
               f'    local g1meta_note : char {n}[note0]',
               f'    char {n}[g1_metadata_note] "`g1meta_note\'"',
               '}', 'else {', f'    notes replace {n} in `g1meta_note\': {d["note"]}', '}',
               f'local g1meta_actual : variable label {n}',
               f'assert "`g1meta_actual\'"=={label}',
               f'local g1meta_saved : char {n}[note`g1meta_note\']',
               f'assert "`g1meta_saved\'"=={note}']
        verify += [f'local g1meta_actual : variable label {n}',
                   f'assert "`g1meta_actual\'"=={label}',
                   f'local g1meta_note : char {n}[g1_metadata_note]',
                   'assert real("`g1meta_note\'")>=1 & !missing(real("`g1meta_note\'"))',
                   f'local g1meta_saved : char {n}[note`g1meta_note\']',
                   f'assert "`g1meta_saved\'"=={note}',
                   f'local g1meta_definition : char {n}[g1_definition]',
                   f'assert "`g1meta_definition\'"=={stata_literal(d["definition"])}']
    do += [f'char _dta[g1_metadata_version] "{VERSION}"',
           'char _dta[g1_metadata_scope] "Labels/notes only; source flags retained after masking"',
           'display "G1_METADATA_LABELS_AND_NOTES_PASS: 516"']
    (out/'labels_and_notes.do').write_text('\n'.join(do)+'\n')
    verify += ['display "G1_SERIALIZED_METADATA_PASS: 516"']
    (out/'verify_metadata.do').write_text('\n'.join(verify)+'\n')
    (out/'CODEBOOK.md').write_text('# G1 final dataset: variable definitions\n\n'
        'Grain: one fictional company-year. Values are obscured before panel construction and G1. '
        'Labels do not certify actual linkage, units or real-input TFP. Source quality categories '
        'are retained after masking; they need not agree with thresholds recalculated on masked numbers.\n\n'
        'In Stata: `describe`, `lookfor productivity`, `notes workers`, or `notes dev_nominal_tfp_lp`. '
        'Select a variable in Data Browser and read its Label/Notes properties.\n\n'
        + '\n'.join(f'## {d["name"]}\n\n**{d["label"]}**\n\n{d["note"][8:]}\n' for d in rows))
    receipt=dict(status='PASS',version=VERSION,variables=len(rows),label_limit=80,
        schema_sha256=hashlib.sha256('\n'.join(names).encode()).hexdigest(),
        files={p.name:sha(p) for p in [out/'labels_and_notes.do',out/'verify_metadata.do',out/'variable_dictionary.csv',out/'CODEBOOK.md']},
        definitions_sha256=sha(Path(__file__).with_name('definitions.py')),
        compiler_sha256=sha(Path(__file__)))
    write_json(out/'contract.json',receipt)
    return rows,receipt

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('input',type=Path);p.add_argument('output',type=Path)
    a=p.parse_args();_,r=compile_metadata(a.input,a.output);print(json.dumps(r,indent=2))
